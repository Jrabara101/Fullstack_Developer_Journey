function generatePriceHistory(days: number, baseCents: number, lowCents: number) {
  const history: { date: string; priceCents: number; msrpCents: number }[] = [];
  const now = new Date();
  
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    
    // Simulate realistic historical price fluctuation
    let dayPrice = baseCents;
    if (i > days - 5) {
      dayPrice = baseCents; // recent price
    } else if (i >= 20 && i <= 25) {
      dayPrice = lowCents; // Flash sale dip
    } else if (i % 7 === 0) {
      dayPrice = Math.round(baseCents * 0.94); // Weekend promo
    } else {
      const wobble = (Math.sin(i * 0.4) * 0.05 + 1);
      dayPrice = Math.round(baseCents * wobble);
    }
    
    const msrp = Math.round(baseCents * 1.15);
    history.push({ date: dateStr, priceCents: Math.max(lowCents, dayPrice), msrpCents: msrp });
  }
  return history;
}

